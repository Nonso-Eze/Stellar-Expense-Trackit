import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  // Required for Stellar SDK (uses Node.js crypto modules)
  webpack: (config, { isServer }) => {
    if (!isServer) {
      config.resolve.fallback = {
        ...config.resolve.fallback,
        fs: false,
        net: false,
        tls: false,
        crypto: false,
      };
    }
    return config;
  },
};

export default nextConfig;
